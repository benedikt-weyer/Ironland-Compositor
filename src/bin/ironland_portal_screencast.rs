enum PwMsg {
    Frame(Vec<u8>),
    Quit,
}

/// State shared between a stream's pump and PipeWire threads.
struct StreamShared {
    stop: AtomicBool,
    /// Whether a consumer has the node in the streaming state; the pump
    /// idles (no capture requests at all) while nobody is reading.
    streaming: AtomicBool,
    in_flight: AtomicUsize,
}

struct StreamHandle {
    shared: Arc<StreamShared>,
    tx: pw::channel::Sender<PwMsg>,
}

impl StreamHandle {
    fn close(&self) {
        self.shared.stop.store(true, Ordering::Relaxed);
        let _ = self.tx.send(PwMsg::Quit);
    }
}

struct StartedStream {
    handle: StreamHandle,
    node_id: u32,
    size: (u32, u32),
}

/// The capture thread: negotiates a session on the output called `output_name`
/// (reporting its size through `init`), then captures frames forever,
/// forwarding each to the PipeWire thread, until stopped.
fn run_pump(
    output_name: String,
    init: mpsc::Sender<Result<(u32, u32), String>>,
    tx: pw::channel::Sender<PwMsg>,
    shared: Arc<StreamShared>,
) {
    let fail = |msg: String| {
        let _ = init.send(Err(msg));
    };
    let Some(conn) = connect_capture_socket() else {
        return fail("no privileged capture socket available".into());
    };
    let (globals, mut queue) = match registry_queue_init::<App>(&conn) {
        Ok(v) => v,
        Err(err) => return fail(format!("registry init failed: {err}")),
    };
    let qh = queue.handle();

    let shm = match globals.bind::<wl_shm::WlShm, _, _>(&qh, 1..=1, ()) {
        Ok(v) => v,
        Err(err) => return fail(format!("no wl_shm: {err}")),
    };
    let mut app = App::default();
    let output = bind_outputs(&globals, &mut queue, &mut app)
        .into_iter()
        .find(|(name, _)| *name == output_name)
        .map(|(_, output)| output);
    let Some(output) = output else {
        return fail(format!("no output called {output_name}"));
    };
    let Ok(source_manager) =
        globals.bind::<ExtOutputImageCaptureSourceManagerV1, _, _>(&qh, 1..=1, ())
    else {
        return fail("compositor doesn't support ext-image-capture-source-v1".into());
    };
    let Ok(copy_manager) = globals.bind::<ExtImageCopyCaptureManagerV1, _, _>(&qh, 1..=1, ())
    else {
        return fail("compositor doesn't support ext-image-copy-capture-v1".into());
    };

    let source = source_manager.create_source(&output, &qh, ());
    // The cursor is composited into the frame by the compositor already.
    let session = copy_manager.create_session(&source, Options::empty(), &qh, ());

    if !wait_until(
        &conn,
        &mut queue,
        &mut app,
        REQUEST_TIMEOUT,
        &shared.stop,
        |a| a.session.done || a.session.stopped,
    ) || app.session.stopped
    {
        return fail("capture session negotiation failed".into());
    }
    let Some((width, height)) = app.session.buffer_size else {
        return fail("no buffer_size advertised".into());
    };
    if !app.session.xrgb_offered {
        return fail("compositor didn't offer Xrgb8888 shm capture".into());
    }

    let stride = width * BYTES_PER_PIXEL;
    let pool_size = u64::from(stride) * u64::from(height);
    let file = match anon_file(pool_size) {
        Ok(f) => f,
        Err(err) => return fail(format!("failed to create shm buffer: {err}")),
    };
    let pool = shm.create_pool(file.as_fd(), pool_size as i32, &qh, ());
    let buffer = pool.create_buffer(
        0,
        width as i32,
        height as i32,
        stride as i32,
        wl_shm::Format::Xrgb8888,
        &qh,
        (),
    );

    let _ = init.send(Ok((width, height)));
    drop(init);

    let mut last_frame: Option<Vec<u8>> = None;
    let mut last_sent = Instant::now();
    let mut pixels = vec![0u8; pool_size as usize];

    while !shared.stop.load(Ordering::Relaxed) {
        if !shared.streaming.load(Ordering::Relaxed)
            || shared.in_flight.load(Ordering::Relaxed) >= MAX_IN_FLIGHT
        {
            std::thread::sleep(Duration::from_millis(20));
            continue;
        }

        app.frame = FrameState::default();
        let frame = session.create_frame(&qh, ());
        frame.attach_buffer(&buffer);
        frame.damage_buffer(0, 0, width as i32, height as i32);
        frame.capture();

        let finished = wait_until(
            &conn,
            &mut queue,
            &mut app,
            REQUEST_TIMEOUT,
            &shared.stop,
            |a| a.frame.ready || a.frame.failed || a.session.stopped,
        );
        frame.destroy();
        if app.session.stopped {
            break;
        }
        if app.session.buffer_size != Some((width, height)) {
            eprintln!("ironland-portal-screencast: output mode changed, ending stream");
            break;
        }
        if !finished {
            continue;
        }

        if app.frame.ready && file.read_exact_at(&mut pixels, 0).is_ok() {
            last_frame = Some(pixels.clone());
            last_sent = Instant::now();
            shared.in_flight.fetch_add(1, Ordering::Relaxed);
            if tx.send(PwMsg::Frame(pixels.clone())).is_err() {
                break;
            }
        } else {
            // Nothing new on screen (or not allowed yet): keep the last
            // frame fresh for consumers, otherwise try again shortly.
            if let Some(frame) = &last_frame
                && last_sent.elapsed() >= KEEPALIVE
            {
                last_sent = Instant::now();
                shared.in_flight.fetch_add(1, Ordering::Relaxed);
                if tx.send(PwMsg::Frame(frame.clone())).is_err() {
                    break;
                }
            }
            std::thread::sleep(RETRY_INTERVAL);
        }
    }

    session.destroy();
    source.destroy();
    let _ = tx.send(PwMsg::Quit);
}

fn format_pod(width: u32, height: u32) -> Vec<u8> {
    let obj = spa::pod::object!(
        spa::utils::SpaTypes::ObjectParamFormat,
        spa::param::ParamType::EnumFormat,
        spa::pod::property!(
            spa::param::format::FormatProperties::MediaType,
            Id,
            spa::param::format::MediaType::Video
        ),
        spa::pod::property!(
            spa::param::format::FormatProperties::MediaSubtype,
            Id,
            spa::param::format::MediaSubtype::Raw
        ),
        spa::pod::property!(
            spa::param::format::FormatProperties::VideoFormat,
            Id,
            spa::param::video::VideoFormat::BGRx
        ),
        spa::pod::property!(
            spa::param::format::FormatProperties::VideoSize,
            Rectangle,
            spa::utils::Rectangle { width, height }
        ),
        spa::pod::property!(
            spa::param::format::FormatProperties::VideoFramerate,
            Choice,
            Range,
            Fraction,
            spa::utils::Fraction { num: 60, denom: 1 },
            spa::utils::Fraction { num: 0, denom: 1 },
            spa::utils::Fraction {
                num: 1000,
                denom: 1
            }
        ),
    );
    serialize_pod(obj)
}

/// A `spa_param_buffers` key as a `property!` key (the macro wants
/// something with `as_raw()`).
struct BuffersKey(u32);
impl BuffersKey {
    fn as_raw(&self) -> u32 {
        self.0
    }
}

fn buffers_pod(width: u32, height: u32) -> Vec<u8> {
    let stride = (width * BYTES_PER_PIXEL) as i32;
    let size = stride * height as i32;
    let data_types = (1i32 << spa::sys::SPA_DATA_MemFd) | (1i32 << spa::sys::SPA_DATA_MemPtr);
    let obj = spa::pod::object!(
        spa::utils::SpaTypes::ObjectParamBuffers,
        spa::param::ParamType::Buffers,
        spa::pod::Property {
            key: spa::sys::SPA_PARAM_BUFFERS_buffers,
            flags: spa::pod::PropertyFlags::empty(),
            value: spa::pod::Value::Choice(spa::pod::ChoiceValue::Int(spa::utils::Choice(
                spa::utils::ChoiceFlags::empty(),
                spa::utils::ChoiceEnum::Range {
                    default: 4,
                    min: 2,
                    max: 8,
                },
            ))),
        },
        spa::pod::property!(BuffersKey(spa::sys::SPA_PARAM_BUFFERS_blocks), Int, 1),
        spa::pod::property!(BuffersKey(spa::sys::SPA_PARAM_BUFFERS_size), Int, size),
        spa::pod::property!(BuffersKey(spa::sys::SPA_PARAM_BUFFERS_stride), Int, stride),
        spa::pod::Property {
            key: spa::sys::SPA_PARAM_BUFFERS_dataType,
            flags: spa::pod::PropertyFlags::empty(),
            value: spa::pod::Value::Choice(spa::pod::ChoiceValue::Int(spa::utils::Choice(
                spa::utils::ChoiceFlags::empty(),
                spa::utils::ChoiceEnum::Flags {
                    default: data_types,
                    flags: vec![data_types],
                },
            ))),
        },
    );
    serialize_pod(obj)
}

fn serialize_pod(obj: spa::pod::Object) -> Vec<u8> {
    spa::pod::serialize::PodSerializer::serialize(
        std::io::Cursor::new(Vec::new()),
        &spa::pod::Value::Object(obj),
    )
    .expect("pod serialization cannot fail for in-memory values")
    .0
    .into_inner()
}

/// The PipeWire thread: publishes a video source node of `width`x`height`
/// and copies each [`PwMsg::Frame`] into the node's next free buffer.
/// Reports the node id (or why it couldn't be created) through `ready`.
fn run_pipewire(
    width: u32,
    height: u32,
    rx: pw::channel::Receiver<PwMsg>,
    shared: Arc<StreamShared>,
    ready: mpsc::Sender<Result<u32, String>>,
) {
    let result = (|| -> Result<(), pw::Error> {
        let mainloop = pw::main_loop::MainLoopRc::new(None)?;
        let context = pw::context::ContextRc::new(&mainloop, None)?;
        let core = context.connect_rc(None)?;

        let stream = pw::stream::StreamRc::new(
            core.clone(),
            "ironland-screencast",
            properties! {
                *pw::keys::MEDIA_TYPE => "Video",
                *pw::keys::MEDIA_CATEGORY => "Capture",
                *pw::keys::MEDIA_ROLE => "Screen",
            },
        )?;

        struct Listener {
            shared: Arc<StreamShared>,
            ready: Option<mpsc::Sender<Result<u32, String>>>,
            width: u32,
            height: u32,
        }
        let _listener = stream
            .add_local_listener_with_user_data(Listener {
                shared: shared.clone(),
                ready: Some(ready.clone()),
                width,
                height,
            })
            .state_changed(|stream, data, _old, new| {
                use pw::stream::StreamState;
                data.shared
                    .streaming
                    .store(matches!(new, StreamState::Streaming), Ordering::Relaxed);
                match new {
                    StreamState::Paused | StreamState::Streaming => {
                        if let Some(ready) = data.ready.take() {
                            let _ = ready.send(Ok(stream.node_id()));
                        }
                    }
                    StreamState::Error(msg) => {
                        if let Some(ready) = data.ready.take() {
                            let _ = ready.send(Err(msg));
                        }
                        data.shared.stop.store(true, Ordering::Relaxed);
                    }
                    StreamState::Unconnected | StreamState::Connecting => {}
                }
            })
            .param_changed(|stream, data, id, param| {
                if param.is_none() || id != spa::param::ParamType::Format.as_raw() {
                    return;
                }
                let bytes = buffers_pod(data.width, data.height);
                if let Some(pod) = spa::pod::Pod::from_bytes(&bytes) {
                    let _ = stream.update_params(&mut [pod]);
                }
            })
            .register()?;

        let format = format_pod(width, height);
        let mut params = [spa::pod::Pod::from_bytes(&format).expect("valid format pod")];
        stream.connect(
            spa::utils::Direction::Output,
            None,
            pw::stream::StreamFlags::DRIVER
                | pw::stream::StreamFlags::ALLOC_BUFFERS
                | pw::stream::StreamFlags::MAP_BUFFERS,
            &mut params,
        )?;

        let stride = width * BYTES_PER_PIXEL;
        let quit_loop = mainloop.clone();
        let _receiver = rx.attach(mainloop.loop_(), {
            let stream = stream.clone();
            let shared = shared.clone();
            move |msg| match msg {
                PwMsg::Quit => quit_loop.quit(),
                PwMsg::Frame(pixels) => {
                    shared.in_flight.fetch_sub(1, Ordering::Relaxed);
                    // No free buffer (or no consumer yet) just drops the frame.
                    if let Some(mut buffer) = stream.dequeue_buffer() {
                        if let Some(data) = buffer.datas_mut().first_mut() {
                            let written = data.data().map(|dst| {
                                let n = dst.len().min(pixels.len());
                                dst[..n].copy_from_slice(&pixels[..n]);
                                n
                            });
                            if let Some(n) = written {
                                let chunk = data.chunk_mut();
                                *chunk.offset_mut() = 0;
                                *chunk.stride_mut() = stride as i32;
                                *chunk.size_mut() = n as u32;
                            }
                        }
                        drop(buffer);
                        let _ = stream.trigger_process();
                    }
                }
            }
        });

        mainloop.run();
        let _ = stream.disconnect();
        Ok(())
    })();

    if let Err(err) = result {
        let _ = ready.send(Err(format!("pipewire error: {err}")));
    }
    shared.stop.store(true, Ordering::Relaxed);
}

/// Starts capturing the output called `output_name` into a new PipeWire node.
fn start_stream(output_name: String) -> Result<StartedStream, String> {
    let shared = Arc::new(StreamShared {
        stop: AtomicBool::new(false),
        streaming: AtomicBool::new(false),
        in_flight: AtomicUsize::new(0),
    });
    let (tx, rx) = pw::channel::channel::<PwMsg>();

    let (init_tx, init_rx) = mpsc::channel();
    {
        let tx = tx.clone();
        let shared = shared.clone();
        std::thread::spawn(move || run_pump(output_name, init_tx, tx, shared));
    }
    let (width, height) = init_rx
        .recv_timeout(REQUEST_TIMEOUT)
        .map_err(|_| "timed out waiting for the capture session".to_string())??;

    let (ready_tx, ready_rx) = mpsc::channel();
    {
        let shared = shared.clone();
        std::thread::spawn(move || run_pipewire(width, height, rx, shared, ready_tx));
    }
    let node_id = ready_rx
        .recv_timeout(Duration::from_secs(10))
        .map_err(|_| "timed out waiting for the PipeWire node".to_string())
        .and_then(|r| r);

    let handle = StreamHandle { shared, tx };
    match node_id {
        Ok(node_id) => Ok(StartedStream {
            handle,
            node_id,
            size: (width, height),
        }),
        Err(err) => {
            handle.close();
            Err(err)
        }
    }
}

