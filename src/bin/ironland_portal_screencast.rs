struct SessionInfo {
    app_id: String,
    multiple: bool,
    streams: Vec<StreamHandle>,
}

struct Shared {
    store: Mutex<Store>,
    sessions: Mutex<HashMap<String, SessionInfo>>,
}

impl Shared {
    fn close_session(&self, session_handle: &str) {
        if let Some(info) = self.sessions.lock().unwrap().remove(session_handle) {
            for stream in &info.streams {
                stream.close();
            }
        }
    }
}

/// `org.freedesktop.impl.portal.Session`, registered at each session's own
/// object path so `xdg-desktop-portal` can route the app's `Session.Close`.
struct SessionIface {
    shared: Arc<Shared>,
    connection: zbus::Connection,
    session_handle: OwnedObjectPath,
}

#[interface(name = "org.freedesktop.impl.portal.Session")]
impl SessionIface {
    async fn close(&self) {
        self.shared.close_session(self.session_handle.as_str());
        let _ = self
            .connection
            .object_server()
            .remove::<SessionIface, _>(&self.session_handle)
            .await;
    }

    #[zbus(property, name = "version")]
    fn version(&self) -> u32 {
        1
    }
}

#[derive(Debug, Default, SerializeDict, Type)]
#[zvariant(signature = "dict")]
struct StartResults {
    streams: Vec<(u32, HashMap<String, OwnedValue>)>,
}

struct ScreenCastIface {
    shared: Arc<Shared>,
    connection: zbus::Connection,
}

fn truthy(options: &HashMap<String, OwnedValue>, key: &str) -> bool {
    options
        .get(key)
        .and_then(|v| bool::try_from(v).ok())
        .unwrap_or(false)
}

/// Runs `work` on its own thread (it blocks on prompts and PipeWire) and
/// awaits the result without stalling the D-Bus executor.
async fn offload<T: Send + 'static>(work: impl FnOnce() -> T + Send + 'static) -> Option<T> {
    let (tx, rx) = async_channel::bounded(1);
    std::thread::spawn(move || {
        let _ = tx.send_blocking(work());
    });
    rx.recv().await.ok()
}

#[interface(name = "org.freedesktop.impl.portal.ScreenCast")]
impl ScreenCastIface {
    #[zbus(property, name = "version")]
    fn version(&self) -> u32 {
        4
    }

    #[zbus(property, name = "AvailableSourceTypes")]
    fn available_source_types(&self) -> u32 {
        SOURCE_TYPE_MONITOR
    }

    #[zbus(property, name = "AvailableCursorModes")]
    fn available_cursor_modes(&self) -> u32 {
        CURSOR_MODE_EMBEDDED
    }

    async fn create_session(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        app_id: String,
        _options: HashMap<String, OwnedValue>,
    ) -> (u32, HashMap<String, OwnedValue>) {
        let owned: OwnedObjectPath = session_handle.to_owned().into();
        self.shared.sessions.lock().unwrap().insert(
            owned.to_string(),
            SessionInfo {
                app_id,
                multiple: false,
                streams: Vec::new(),
            },
        );

        let iface = SessionIface {
            shared: self.shared.clone(),
            connection: self.connection.clone(),
            session_handle: owned.clone(),
        };
        if let Err(err) = self
            .connection
            .object_server()
            .at(owned.clone(), iface)
            .await
        {
            eprintln!(
                "ironland-portal-screencast: failed to register {SESSION_IFACE} at {owned}: {err}"
            );
            self.shared.close_session(owned.as_str());
            return (2, HashMap::new());
        }
        (0, HashMap::new())
    }

    async fn select_sources(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        _app_id: String,
        options: HashMap<String, OwnedValue>,
    ) -> (u32, HashMap<String, OwnedValue>) {
        let mut sessions = self.shared.sessions.lock().unwrap();
        match sessions.get_mut(session_handle.as_str()) {
            Some(info) => {
                info.multiple = truthy(&options, "multiple");
                (0, HashMap::new())
            }
            None => (2, HashMap::new()),
        }
    }

    #[allow(clippy::too_many_arguments)]
    async fn start(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        app_id: String,
        _parent_window: String,
        _options: HashMap<String, OwnedValue>,
    ) -> (u32, StartResults) {
        let shared = self.shared.clone();
        let session_handle = session_handle.to_string();
        let outcome = offload(move || start_session(&shared, &session_handle, &app_id)).await;
        match outcome {
            Some(Ok(results)) => (0, results),
            Some(Err(StartError::Denied)) => (1, StartResults::default()),
            Some(Err(StartError::Failed(err))) => {
                eprintln!("ironland-portal-screencast: start failed: {err}");
                (2, StartResults::default())
            }
            None => (2, StartResults::default()),
        }
    }
}

enum StartError {
    Denied,
    Failed(String),
}

/// The blocking body of `Start()`: permission check, then one stream per
/// selected output.
fn start_session(
    shared: &Shared,
    session_handle: &str,
    app_id: &str,
) -> Result<StartResults, StartError> {
    let multiple = {
        let sessions = shared.sessions.lock().unwrap();
        let info = sessions
            .get(session_handle)
            .ok_or_else(|| StartError::Failed("unknown session".into()))?;
        info.multiple
    };

    let grant = shared.store.lock().unwrap().grants.get(app_id).copied();
    let allowed = match grant {
        Some(Grant::Allow) => true,
        Some(Grant::Deny) => false,
        None => {
            let shown_id = if app_id.is_empty() {
                "An application"
            } else {
                app_id
            };
            let answer = ask_permission(shown_id, "record your screen").unwrap_or(false);
            let mut store = shared.store.lock().unwrap();
            store.grants.insert(
                app_id.to_string(),
                if answer { Grant::Allow } else { Grant::Deny },
            );
            store.save();
            answer
        }
    };
    if !allowed {
        return Err(StartError::Denied);
    }

    let outputs = list_outputs();
    if outputs.is_empty() {
        return Err(StartError::Failed("no outputs available".into()));
    }
    let shown_id = if app_id.is_empty() {
        "An application"
    } else {
        app_id
    };
    let wanted: Vec<String> = if multiple || outputs.len() == 1 {
        outputs
    } else {
        // More than one monitor: let the user pick which one, on screen
        // (each monitor shows its number). A compositor without the
        // chooser falls back to the first output.
        match ask_output(shown_id, "record your screen") {
            Ok(name) if outputs.contains(&name) => vec![name],
            Ok(name) => {
                return Err(StartError::Failed(format!(
                    "chosen output {name} is no longer available"
                )));
            }
            Err(ChooseError::Cancelled) => return Err(StartError::Denied),
            Err(ChooseError::Unsupported) => outputs.into_iter().take(1).collect(),
        }
    };

    let mut started = Vec::new();
    for name in wanted {
        match start_stream(name) {
            Ok(stream) => started.push(stream),
            Err(err) => {
                for stream in &started {
                    stream.handle.close();
                }
                return Err(StartError::Failed(err));
            }
        }
    }

    let mut results = StartResults::default();
    for stream in &started {
        let mut props: HashMap<String, OwnedValue> = HashMap::new();
        let ints = |(a, b): (i32, i32)| Value::from((a, b)).try_to_owned().unwrap();
        props.insert(
            "source_type".into(),
            Value::from(SOURCE_TYPE_MONITOR).try_to_owned().unwrap(),
        );
        props.insert(
            "size".into(),
            ints((stream.size.0 as i32, stream.size.1 as i32)),
        );
        results.streams.push((stream.node_id, props));
    }

    let mut sessions = shared.sessions.lock().unwrap();
    match sessions.get_mut(session_handle) {
        Some(info) => {
            let _ = &info.app_id;
            info.streams
                .extend(started.into_iter().map(|stream| stream.handle));
            Ok(results)
        }
        None => {
            // Closed while we were starting up.
            for stream in &started {
                stream.handle.close();
            }
            Err(StartError::Failed("session closed during start".into()))
        }
    }
}

fn main() {
    pw::init();

    let shared = Arc::new(Shared {
        store: Mutex::new(Store::load()),
        sessions: Mutex::new(HashMap::new()),
    });

    let connection = match async_io::block_on(async {
        zbus::connection::Builder::session()?
            .name(BUS_NAME)?
            .build()
            .await
    }) {
        Ok(conn) => conn,
        Err(err) => {
            eprintln!("ironland-portal-screencast: failed to connect to session bus: {err}");
            std::process::exit(1);
        }
    };

    let iface = ScreenCastIface {
        shared,
        connection: connection.clone(),
    };
    if let Err(err) = async_io::block_on(connection.object_server().at(PORTAL_PATH, iface)) {
        eprintln!("ironland-portal-screencast: failed to register ScreenCast interface: {err}");
        std::process::exit(1);
    }

    loop {
        std::thread::sleep(Duration::from_secs(3600));
    }
}
