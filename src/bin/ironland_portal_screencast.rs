fn connect_capture_socket() -> Option<Connection> {
    let socket_name = std::env::var("IRONLAND_CAPTURE_SOCKET").ok()?;
    let runtime_dir = std::env::var("XDG_RUNTIME_DIR").ok()?;
    let path = PathBuf::from(runtime_dir).join(socket_name);
    let stream = std::os::unix::net::UnixStream::connect(path).ok()?;
    Connection::from_socket(stream).ok()
}

/// Dispatches `queue` until `done` holds, `timeout` passes, or `stop` is
/// set, polling the socket with a short timeout so `stop` is noticed
/// promptly. Returns whether `done` held.
fn wait_until(
    conn: &Connection,
    queue: &mut EventQueue<App>,
    app: &mut App,
    timeout: Duration,
    stop: &AtomicBool,
    mut done: impl FnMut(&App) -> bool,
) -> bool {
    let deadline = Instant::now() + timeout;
    loop {
        if queue.dispatch_pending(app).is_err() {
            return false;
        }
        if done(app) {
            return true;
        }
        if stop.load(Ordering::Relaxed) || Instant::now() >= deadline {
            return false;
        }
        if conn.flush().is_err() {
            return false;
        }
        let Some(guard) = queue.prepare_read() else {
            continue;
        };
        let fd: BorrowedFd<'_> = guard.connection_fd();
        let mut fds = [PollFd::new(&fd, PollFlags::IN)];
        match poll(
            &mut fds,
            Some(&rustix::time::Timespec {
                tv_sec: 0,
                tv_nsec: 100_000_000,
            }),
        ) {
            Ok(n) if n > 0 => {
                if guard.read().is_err() {
                    return false;
                }
            }
            _ => drop(guard),
        }
    }
}

/// Asks the compositor to show a permission prompt and blocks for the
/// user's answer. `None` on any protocol/timeout failure (a denial).
fn ask_permission(app_id: &str, reason: &str) -> Option<bool> {
    let conn = connect_capture_socket()?;
    let (globals, mut queue) = registry_queue_init::<App>(&conn).ok()?;
    let qh = queue.handle();
    let manager = globals
        .bind::<IronlandPermissionPromptManagerV1, _, _>(&qh, 1..=1, ())
        .ok()?;

    let mut app = App::default();
    manager.prompt(app_id.to_string(), reason.to_string(), &qh, ());

    let stop = AtomicBool::new(false);
    if !wait_until(&conn, &mut queue, &mut app, REQUEST_TIMEOUT, &stop, |a| {
        a.prompt_answer.is_some()
    }) {
        return None;
    }
    app.prompt_answer
}

/// Binds every `wl_output` the registry lists and waits for their names,
/// returning `(name, output)` pairs in registry order. An output that
/// doesn't report a name (`wl_output` older than version 4) is called
/// `output-<index>`.
fn bind_outputs(
    globals: &wayland_client::globals::GlobalList,
    queue: &mut EventQueue<App>,
    app: &mut App,
) -> Vec<(String, WlOutput)> {
    let qh = queue.handle();
    let globals_list: Vec<(u32, u32)> = globals.contents().with_list(|list| {
        list.iter()
            .filter(|g| g.interface == "wl_output")
            .map(|g| (g.name, g.version))
            .collect()
    });
    let outputs: Vec<WlOutput> = globals_list
        .iter()
        .enumerate()
        .map(|(index, (name, version))| {
            globals
                .registry()
                .bind(*name, (*version).min(4), &qh, index)
        })
        .collect();
    let _ = queue.roundtrip(app);
    outputs
        .into_iter()
        .enumerate()
        .map(|(index, output)| {
            let name = app
                .output_names
                .get(&index)
                .cloned()
                .unwrap_or_else(|| format!("output-{index}"));
            (name, output)
        })
        .collect()
}

/// The names of the outputs the capture socket advertises.
fn list_outputs() -> Vec<String> {
    let Some(conn) = connect_capture_socket() else {
        return Vec::new();
    };
    let Ok((globals, mut queue)) = registry_queue_init::<App>(&conn) else {
        return Vec::new();
    };
    let mut app = App::default();
    bind_outputs(&globals, &mut queue, &mut app)
        .into_iter()
        .map(|(name, _)| name)
        .collect()
}

enum ChooseError {
    /// The user dismissed the chooser (or it timed out).
    Cancelled,
    /// The compositor can't show a chooser; the caller falls back.
    Unsupported,
}

/// Asks the compositor to show its monitor chooser and blocks for the
/// user's pick, returning the chosen output's name.
fn ask_output(app_id: &str, reason: &str) -> Result<String, ChooseError> {
    let conn = connect_capture_socket().ok_or(ChooseError::Unsupported)?;
    let (globals, mut queue) =
        registry_queue_init::<App>(&conn).map_err(|_| ChooseError::Unsupported)?;
    let qh = queue.handle();
    let manager = globals
        .bind::<IronlandPermissionPromptManagerV1, _, _>(&qh, 2..=2, ())
        .map_err(|_| ChooseError::Unsupported)?;

    let mut app = App::default();
    manager.choose_output(app_id.to_string(), reason.to_string(), &qh, ());

    let stop = AtomicBool::new(false);
    if !wait_until(&conn, &mut queue, &mut app, REQUEST_TIMEOUT, &stop, |a| {
        a.chooser_answer.is_some()
    }) {
        return Err(ChooseError::Cancelled);
    }
    app.chooser_answer.flatten().ok_or(ChooseError::Cancelled)
}

/// Creates an anonymous (create + immediately unlink) file of `size` bytes
/// for use as a `wl_shm` pool.
fn anon_file(size: u64) -> std::io::Result<File> {
    let path = std::env::temp_dir().join(format!(
        "ironland-screencast-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or_default()
    ));
    let file = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(true)
        .open(&path)?;
    file.set_len(size)?;
    let _ = std::fs::remove_file(&path);
    Ok(file)
}

