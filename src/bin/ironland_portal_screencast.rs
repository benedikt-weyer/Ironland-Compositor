//! `org.freedesktop.impl.portal.ScreenCast` backend for
//! `xdg-desktop-portal`: what OBS, browsers and other PipeWire-based
//! recorders go through to record a monitor.
//!
//! It bridges two things, both over the compositor's *privileged* capture
//! Wayland socket (`$IRONLAND_CAPTURE_SOCKET`, the same one
//! `ironland-portal-screenshot` uses - see that binary's module doc and
//! `crate::screencopy`):
//!
//! - **In**: `ext-image-capture-source-v1` + `ext-image-copy-capture-v1`,
//!   repeatedly capturing one output into a shared-memory buffer (one
//!   "pump" thread per stream; `crate::screencopy` does the actual pixel
//!   copy and gates every capturer, this binary included, by executable).
//! - **Out**: a PipeWire video node (one thread per stream, running a
//!   PipeWire main loop) whose buffers those frames are copied into. Its
//!   node id is what `Start()` returns; `xdg-desktop-portal` itself opens
//!   the PipeWire remote and hands the app that fd + node id, so this
//!   backend never implements `OpenPipeWireRemote`.
//!
//! Packaging: `resources/ironland-screencast.portal` registers this under
//! its own bus name (two processes can't own the same one); the matching
//! `.service` file's `Exec=` is generated by `flake.nix`.
//!
//! ## Permission model
//!
//! Two independent layers, same as the Screenshot backend: a persisted
//! per-`app_id` decision (`$XDG_CONFIG_HOME/ironland-compositor/
//! screencast-permissions.json`), asked for on first use through
//! `ironland-permission-prompt-v1`; and the compositor's own per-executable
//! gate on every actual capture. On a fresh install the compositor's gate
//! fails this binary's first captures until the user approves
//! `ironland-portal-screencast` itself - the pump just keeps retrying, so
//! the stream starts delivering frames once that's answered.
//!
//! ## Scope
//!
//! - Monitor sources only (`AvailableSourceTypes = MONITOR`). A
//!   non-`multiple` request on a multi-monitor setup shows the compositor's
//!   own monitor chooser (`ironland-permission-prompt-v1`'s `choose_output`:
//!   a numbered list, with the same number drawn in each monitor's top-left
//!   corner) and records the one picked; with a single monitor, or on a
//!   compositor without the chooser, it records the first output. A
//!   `multiple` request gets every output as its own stream.
//! - The cursor is whatever the compositor composites into the frame
//!   (`AvailableCursorModes = EMBEDDED`); it can't be hidden or sent as
//!   metadata.
//! - Frames are `BGRx` in shared memory (no dmabuf), at the rate the
//!   compositor renders changed frames. A static screen produces no new
//!   frames, so the last one is re-sent about twice a second to keep
//!   consumers that wait for frames alive.
//! - Output mode changes end the stream (the consumer has to reconnect).
//! - Sessions are not restorable (`persist_mode` is ignored).

