//! `org.freedesktop.impl.portal.GlobalShortcuts` backend for
//! `xdg-desktop-portal`, bridging it to `ironland-shortcuts-v1`'s `bind`
//! request (protocol version 2+; see `crate::shortcuts` in the compositor
//! itself and `protocols/ironland-shortcuts-v1.xml`).
//!
//! Like `ironland-workspaces`, this is a small standalone Wayland client -
//! not part of the compositor binary - meant to be D-Bus-activated by
//! `xdg-desktop-portal`. Packaging: `resources/ironland.portal` (checked
//! in, no store paths) registers this as the `GlobalShortcuts` backend;
//! the matching `org.freedesktop.impl.portal.desktop.ironland.service`
//! D-Bus activation file is generated by `flake.nix`'s `packages.default`
//! (its `Exec=` needs that derivation's own `$out`).
//!
//! ## Scope / known limitations
//!
//! This backend has no shortcut-editor UI. A `BindShortcuts` request for a
//! shortcut with no usable `preferred_trigger` option (missing, or not
//! parseable by [`ironland_compositor::keybindings::parse_binding`]'s syntax,
//! e.g. `"ctrl+alt+t"`) is accepted but left untriggered - it's listed by
//! `ListShortcuts`/`ShortcutsChanged` with an empty `trigger_description`
//! and simply never activates. A future version could add a real
//! reassignment UI; until then, apps that don't pass a trigger effectively
//! aren't supported.
//!
//! Bindings are persisted per `app_id` (see [`Store`]) to
//! `$XDG_CONFIG_HOME/ironland-compositor/global-shortcuts.json` so a
//! previously granted trigger survives both this process and the
//! requesting app restarting - required by the portal spec. Note `app_id`
//! is often empty for non-sandboxed apps (xdg-desktop-portal has no better
//! identity for them), so persisted triggers for such apps share a
//! namespace; a real-world deployment mostly cares about sandboxed
//! (Flatpak) callers here, which do get a distinct `app_id`.

