/// Generated client bindings for `ironland-shortcuts-v1` (see
/// `protocols/ironland-shortcuts-v1.xml`) - not in the `wayland-protocols`
/// crate since it's our own, so generated here the same way
/// `crate::ironland_protocols` generates the compositor's server side of
/// it.
mod shortcuts_protocol {
    #![allow(
        dead_code,
        non_camel_case_types,
        unused_imports,
        missing_docs,
        clippy::all
    )]

    use wayland_client;
    use wayland_client::protocol::*;

    pub mod __interfaces {
        use wayland_client::protocol::__interfaces::*;
        wayland_scanner::generate_interfaces!("./protocols/ironland-shortcuts-v1.xml");
    }
    use self::__interfaces::*;

    wayland_scanner::generate_client_code!("./protocols/ironland-shortcuts-v1.xml");
}
use shortcuts_protocol::ironland_shortcut_v1::{self, IronlandShortcutV1};
use shortcuts_protocol::ironland_shortcuts_manager_v1::IronlandShortcutsManagerV1;

fn modifiers_bitmask(m: &KeyModifiers) -> u32 {
    (m.ctrl as u32) | ((m.alt as u32) << 1) | ((m.shift as u32) << 2) | ((m.logo as u32) << 3)
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

// ---------------------------------------------------------------------
// Wayland side: owns the compositor connection, grabs/ungrabs triggers on
// command, and reports presses/releases back to the D-Bus side.
// ---------------------------------------------------------------------

/// A press/release of a bound trigger, reported up to the D-Bus side so it
/// can emit the matching portal signal.
enum PortalEvent {
    Activated {
        session_handle: String,
        shortcut_id: String,
    },
    Deactivated {
        session_handle: String,
        shortcut_id: String,
    },
}

/// A request from the D-Bus side to grab or release a trigger.
enum WaylandCmd {
    Bind {
        session_handle: String,
        shortcut_id: String,
        modifiers: u32,
        keysym: u32,
    },
    UnbindSession {
        session_handle: String,
    },
}

/// User data for a bound `ironland_shortcut_v1` object: which
/// session/shortcut it reports presses/releases for.
struct ShortcutUserData {
    session_handle: String,
    shortcut_id: String,
}

struct WaylandApp {
    manager: Option<IronlandShortcutsManagerV1>,
    bound: HashMap<(String, String), IronlandShortcutV1>,
    events: std::sync::mpsc::Sender<PortalEvent>,
}

impl WaylandApp {
    fn handle_cmd(&mut self, qh: &QueueHandle<Self>, cmd: WaylandCmd) {
        match cmd {
            WaylandCmd::Bind {
                session_handle,
                shortcut_id,
                modifiers,
                keysym,
            } => {
                let Some(manager) = &self.manager else {
                    return;
                };
                let key = (session_handle.clone(), shortcut_id.clone());
                if let Some(old) = self.bound.remove(&key) {
                    old.destroy();
                }
                let resource = manager.bind(
                    modifiers,
                    keysym,
                    qh,
                    ShortcutUserData {
                        session_handle,
                        shortcut_id,
                    },
                );
                self.bound.insert(key, resource);
            }
            WaylandCmd::UnbindSession { session_handle } => {
                self.bound.retain(|(sh, _), resource| {
                    let keep = sh != &session_handle;
                    if !keep {
                        resource.destroy();
                    }
                    keep
                });
            }
        }
    }
}

impl Dispatch<IronlandShortcutV1, ShortcutUserData> for WaylandApp {
    fn event(
        state: &mut Self,
        _proxy: &IronlandShortcutV1,
        event: ironland_shortcut_v1::Event,
        data: &ShortcutUserData,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
    ) {
        let event = match event {
            ironland_shortcut_v1::Event::Pressed { output: _ } => PortalEvent::Activated {
                session_handle: data.session_handle.clone(),
                shortcut_id: data.shortcut_id.clone(),
            },
            ironland_shortcut_v1::Event::Released => PortalEvent::Deactivated {
                session_handle: data.session_handle.clone(),
                shortcut_id: data.shortcut_id.clone(),
            },
        };
        let _ = state.events.send(event);
    }
}

wayland_client::delegate_noop!(WaylandApp: ignore IronlandShortcutsManagerV1);

impl Dispatch<WlRegistry, GlobalListContents> for WaylandApp {
    fn event(
        _state: &mut Self,
        _proxy: &WlRegistry,
        _event: wl_registry::Event,
        _data: &GlobalListContents,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
    ) {
        // Everything needed (the shortcuts manager) is bound once at
        // startup from the initial registry burst - see `run_wayland`.
    }
}

fn run_wayland(events: std::sync::mpsc::Sender<PortalEvent>, cmd_rx: Channel<WaylandCmd>) {
    let conn = match Connection::connect_to_env() {
        Ok(conn) => conn,
        Err(err) => {
            eprintln!(
                "ironland-portal-global-shortcuts: failed to connect to Wayland display: {err}"
            );
            std::process::exit(1);
        }
    };
    let (globals, event_queue) =
        registry_queue_init::<WaylandApp>(&conn).expect("failed to init registry");
    let qh = event_queue.handle();

    let manager = match globals.bind::<IronlandShortcutsManagerV1, _, _>(&qh, 2..=2, ()) {
        Ok(manager) => Some(manager),
        Err(err) => {
            eprintln!(
                "ironland-portal-global-shortcuts: compositor doesn't support \
                 ironland-shortcuts-v1 v2 (bind request) - global shortcuts will never fire: {err}"
            );
            None
        }
    };

    let mut app = WaylandApp {
        manager,
        bound: HashMap::new(),
        events,
    };

    let mut event_loop: EventLoop<WaylandApp> =
        EventLoop::try_new().expect("failed to create event loop");
    let loop_handle = event_loop.handle();
    WaylandSource::new(conn, event_queue)
        .insert(loop_handle.clone())
        .expect("failed to insert Wayland source");

    loop_handle
        .insert_source(cmd_rx, move |event, _, app| {
            if let channel::Event::Msg(cmd) = event {
                app.handle_cmd(&qh, cmd);
            }
        })
        .expect("failed to insert command source");

    event_loop
        .run(None, &mut app, |_| {})
        .expect("event loop error");
}

// ---------------------------------------------------------------------
// Persistence: per-app_id shortcut -> trigger, across restarts.
// ---------------------------------------------------------------------

#[derive(Debug, Clone, Serialize, Deserialize)]
struct PersistedShortcut {
    description: String,
    /// `None` if this shortcut has never gotten a usable trigger (no/
    /// unparseable `preferred_trigger` and no prior binding) - see the
    /// module doc's Scope section.
    trigger: Option<String>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct Store {
    #[serde(flatten)]
    apps: HashMap<String, HashMap<String, PersistedShortcut>>,
}

fn store_path() -> PathBuf {
    let config_home = std::env::var("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|_| {
            PathBuf::from(std::env::var("HOME").unwrap_or_else(|_| "/".to_string())).join(".config")
        });
    config_home
        .join("ironland-compositor")
        .join("global-shortcuts.json")
}

impl Store {
    fn load() -> Self {
        let path = store_path();
        match std::fs::read_to_string(&path) {
            Ok(contents) => serde_json::from_str(&contents).unwrap_or_default(),
            Err(_) => Store::default(),
        }
    }

    fn save(&self) {
        let path = store_path();
        if let Some(parent) = path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        if let Ok(json) = serde_json::to_string_pretty(self)
            && let Ok(mut file) = std::fs::File::create(&path)
        {
            let _ = file.write_all(json.as_bytes());
        }
    }
}

// ---------------------------------------------------------------------
// D-Bus side: `org.freedesktop.impl.portal.GlobalShortcuts`.
// ---------------------------------------------------------------------

struct SessionInfo {
    app_id: String,
}

/// A shortcut bound (successfully triggered or not) for one session, kept
/// around for `ListShortcuts` to answer from and to unbind on session
/// close.
#[derive(Clone)]
struct BoundShortcut {
    description: String,
    trigger: Option<String>,
}

struct Shared {
    store: Store,
    sessions: HashMap<String, SessionInfo>,
    bound: HashMap<(String, String), BoundShortcut>,
    cmd_tx: channel::Sender<WaylandCmd>,
}

fn shortcut_props(
    id: &str,
    description: &str,
    trigger: &Option<String>,
) -> (String, HashMap<String, Value<'static>>) {
    let mut props = HashMap::new();
    props.insert(
        "description".to_string(),
        Value::from(description.to_string()),
    );
    props.insert(
        "trigger_description".to_string(),
        Value::from(trigger.clone().unwrap_or_default()),
    );
    (id.to_string(), props)
}

/// Shared object-server handle for dynamically registering/removing a
/// `org.freedesktop.impl.portal.Session` object per `CreateSession` call,
/// stored alongside the `GlobalShortcuts` interface itself.
struct GlobalShortcutsIface {
    shared: Arc<Mutex<Shared>>,
    connection: zbus::Connection,
}

const SESSION_IFACE: &str = "org.freedesktop.impl.portal.Session";

/// `org.freedesktop.impl.portal.Session`, registered at each session's own
/// object path for the duration of the session (see
/// [`GlobalShortcutsIface::create_session`]) so `xdg-desktop-portal` can
/// route the app's `Session.Close` call to us.
struct SessionIface {
    shared: Arc<Mutex<Shared>>,
    session_handle: String,
}

#[interface(name = "org.freedesktop.impl.portal.Session")]
impl SessionIface {
    fn close(&self) {
        let mut shared = self.shared.lock().unwrap();
        shared.bound.retain(|(sh, _), _| sh != &self.session_handle);
        shared.sessions.remove(&self.session_handle);
        let _ = shared.cmd_tx.send(WaylandCmd::UnbindSession {
            session_handle: self.session_handle.clone(),
        });
    }
}

#[interface(name = "org.freedesktop.impl.portal.GlobalShortcuts")]
impl GlobalShortcutsIface {
    #[zbus(property, name = "version")]
    fn version(&self) -> u32 {
        1
    }

    #[allow(clippy::too_many_arguments)]
    async fn create_session(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        app_id: String,
        _options: HashMap<String, OwnedValue>,
    ) -> (u32, HashMap<String, OwnedValue>) {
        let session_handle_owned: OwnedObjectPath = session_handle.to_owned().into();
        {
            let mut shared = self.shared.lock().unwrap();
            shared
                .sessions
                .insert(session_handle.to_string(), SessionInfo { app_id });
        }

        let session_iface = SessionIface {
            shared: self.shared.clone(),
            session_handle: session_handle.to_string(),
        };
        if let Err(err) = self
            .connection
            .object_server()
            .at(session_handle_owned.clone(), session_iface)
            .await
        {
            eprintln!(
                "ironland-portal-global-shortcuts: failed to register {SESSION_IFACE} at \
                 {session_handle_owned}: {err}"
            );
        }

        (0, HashMap::new())
    }

    #[allow(clippy::too_many_arguments)]
    fn bind_shortcuts(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        shortcuts: Vec<(String, HashMap<String, OwnedValue>)>,
        _parent_window: String,
        _options: HashMap<String, OwnedValue>,
    ) -> (u32, HashMap<String, OwnedValue>) {
        let session_handle = session_handle.to_string();
        let mut results = Vec::new();

        let mut shared = self.shared.lock().unwrap();
        let Some(app_id) = shared
            .sessions
            .get(&session_handle)
            .map(|s| s.app_id.clone())
        else {
            return (2, HashMap::new()); // no such session
        };

        for (id, props) in shortcuts {
            let description = props
                .get("description")
                .and_then(|v| v.downcast_ref::<&str>().ok())
                .map(str::to_string)
                .unwrap_or_default();
            let preferred_trigger = props
                .get("preferred_trigger")
                .and_then(|v| v.downcast_ref::<&str>().ok())
                .map(str::to_string);

            let persisted_trigger = shared
                .store
                .apps
                .get(&app_id)
                .and_then(|s| s.get(&id))
                .and_then(|s| s.trigger.clone());

            let trigger = persisted_trigger.or_else(|| {
                preferred_trigger
                    .as_deref()
                    .filter(|spec| parse_binding(spec).is_some())
                    .map(str::to_string)
            });

            if let Some(spec) = &trigger
                && let Some((mods, keysym)) = parse_binding(spec)
            {
                let _ = shared.cmd_tx.send(WaylandCmd::Bind {
                    session_handle: session_handle.clone(),
                    shortcut_id: id.clone(),
                    modifiers: modifiers_bitmask(&mods),
                    keysym: keysym.raw(),
                });
            }

            shared.store.apps.entry(app_id.clone()).or_default().insert(
                id.clone(),
                PersistedShortcut {
                    description: description.clone(),
                    trigger: trigger.clone(),
                },
            );
            shared.bound.insert(
                (session_handle.clone(), id.clone()),
                BoundShortcut {
                    description: description.clone(),
                    trigger: trigger.clone(),
                },
            );

            results.push(shortcut_props(&id, &description, &trigger));
        }

        shared.store.save();

        let mut out = HashMap::new();
        out.insert(
            "shortcuts".to_string(),
            Value::from(results).try_to_owned().unwrap(),
        );
        (0, out)
    }

    fn list_shortcuts(
        &self,
        _handle: ObjectPath<'_>,
        session_handle: ObjectPath<'_>,
        _options: HashMap<String, OwnedValue>,
    ) -> (u32, HashMap<String, OwnedValue>) {
        let session_handle = session_handle.to_string();
        let shared = self.shared.lock().unwrap();

        let results: Vec<_> = shared
            .bound
            .iter()
            .filter(|((sh, _), _)| sh == &session_handle)
            .map(|((_, id), bound)| shortcut_props(id, &bound.description, &bound.trigger))
            .collect();

        let mut out = HashMap::new();
        out.insert(
            "shortcuts".to_string(),
            Value::from(results).try_to_owned().unwrap(),
        );
        (0, out)
    }

    #[zbus(signal)]
    async fn activated(
        ctxt: &SignalContext<'_>,
        session_handle: ObjectPath<'_>,
        shortcut_id: String,
        timestamp: u64,
        options: HashMap<String, Value<'_>>,
    ) -> zbus::Result<()>;

    #[zbus(signal)]
    async fn deactivated(
        ctxt: &SignalContext<'_>,
        session_handle: ObjectPath<'_>,
        shortcut_id: String,
        timestamp: u64,
        options: HashMap<String, Value<'_>>,
    ) -> zbus::Result<()>;
}

const PORTAL_PATH: &str = "/org/freedesktop/portal/desktop";
const BUS_NAME: &str = "org.freedesktop.impl.portal.desktop.ironland";

fn main() {
    let (event_tx, event_rx) = std::sync::mpsc::channel::<PortalEvent>();
    let (cmd_tx, cmd_rx) = channel::channel::<WaylandCmd>();

    std::thread::spawn(move || run_wayland(event_tx, cmd_rx));

    let shared = Arc::new(Mutex::new(Shared {
        store: Store::load(),
        sessions: HashMap::new(),
        bound: HashMap::new(),
        cmd_tx,
    }));

    let connection = match async_io::block_on(async {
        zbus::connection::Builder::session()?.build().await
    }) {
        Ok(conn) => conn,
        Err(err) => {
            eprintln!("ironland-portal-global-shortcuts: failed to connect to session bus: {err}");
            std::process::exit(1);
        }
    };

    let iface = GlobalShortcutsIface {
        shared: shared.clone(),
        connection: connection.clone(),
    };
    if let Err(err) = async_io::block_on(connection.object_server().at(PORTAL_PATH, iface)) {
        eprintln!(
            "ironland-portal-global-shortcuts: failed to register GlobalShortcuts interface: {err}"
        );
        std::process::exit(1);
    }

    // Claim the bus name only once the interface is exported: xdg-desktop-portal
    // reads this backend's properties (e.g. `AvailableSourceTypes`) once, when
    // the name appears, and never re-reads them, so an interface that shows up
    // after the name leaves it cached as empty.
    if let Err(err) = async_io::block_on(connection.request_name(BUS_NAME)) {
        eprintln!("ironland-portal-global-shortcuts: failed to request bus name: {err}");
        std::process::exit(1);
    }

    // Forward Wayland press/release events to D-Bus signals on a dedicated
    // thread - `Activated`/`Deactivated` are emitted from here, not from
    // inside a method call.
    let emit_conn = connection.clone();
    std::thread::spawn(move || {
        for event in event_rx {
            let (session_handle, shortcut_id, activated) = match event {
                PortalEvent::Activated {
                    session_handle,
                    shortcut_id,
                } => (session_handle, shortcut_id, true),
                PortalEvent::Deactivated {
                    session_handle,
                    shortcut_id,
                } => (session_handle, shortcut_id, false),
            };
            // Owning the path (rather than borrowing `session_handle`)
            // keeps it usable inside the `async move` block below without
            // fighting the borrow checker over `session_handle`'s move.
            let Ok(path) = ObjectPath::try_from(session_handle) else {
                continue;
            };

            let result = async_io::block_on(async {
                let iface_ref = emit_conn
                    .object_server()
                    .interface::<_, GlobalShortcutsIface>(PORTAL_PATH)
                    .await?;
                let ctxt = iface_ref.signal_context();
                if activated {
                    GlobalShortcutsIface::activated(
                        ctxt,
                        path,
                        shortcut_id,
                        now_ms(),
                        HashMap::new(),
                    )
                    .await
                } else {
                    GlobalShortcutsIface::deactivated(
                        ctxt,
                        path,
                        shortcut_id,
                        now_ms(),
                        HashMap::new(),
                    )
                    .await
                }
            });
            if let Err(err) = result {
                eprintln!("ironland-portal-global-shortcuts: failed to emit signal: {err}");
            }
        }
    });

    // Everything happens on background threads/zbus's own executor from
    // here; just block forever.
    loop {
        std::thread::sleep(std::time::Duration::from_secs(3600));
    }
}
